"""Write media/images.toml and media/maps.toml from the build manifests and alt text.

An entry is written only when its WebP exists, the manifest records it, and it has
alt text in alt_text.py. Anything built but lacking alt text is listed, not written.
Run: python3 pipeline/media/build_catalogs.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import maps as map_specs  # noqa: E402
from alt_text import ALT, MAP_ALT  # noqa: E402
from build_images import image_specs  # noqa: E402
from common import CACHE, MEDIA, PUBLIC, write_toml  # noqa: E402

FIELDS = ["id", "title", "artist", "year", "file", "width", "height", "alt", "source_page",
          "license", "credit", "tags"]


def rows_for(kind: str, specs: list[dict], alt: dict[str, str]) -> tuple[list[dict], list[str]]:
    manifest = json.loads((CACHE / f"built_{kind}.json").read_text())
    rows, pending = [], []
    for s in specs:
        rec = manifest.get(s["id"])
        path = PUBLIC / "media" / kind / f"{s['id']}.webp"
        if not rec or not path.exists():
            pending.append(f"{s['id']} (not built)")
            continue
        if s["id"] not in alt:
            pending.append(f"{s['id']} (no alt text)")
            continue
        row = {"id": s["id"], "title": s["title"], "artist": s["artist"], "year": str(s["year"]),
               "file": f"/media/{kind}/{s['id']}.webp", "width": rec["width"], "height": rec["height"],
               "alt": alt[s["id"]], "source_page": rec["source_page"], "license": "Public domain",
               "credit": rec["credit"], "tags": s["tags"]}
        if kind == "maps":
            row["region"] = s["region"]
            row["period"] = s["period"]
        rows.append(row)
    return rows, pending


def main() -> int:
    img_specs, _ = image_specs()
    imgs, img_pending = rows_for("images", img_specs, ALT)
    mps, map_pending = rows_for("maps", map_specs.specs(), MAP_ALT)
    write_toml(MEDIA / "images.toml",
               "# Public domain art for the He Lives library: the Doré Bible (1866), portraits of the\n"
               "# fathers, and the art and finds of the evidence pages. Generated by pipeline/media/build_catalogs.py; files live under public/.",
               "image", imgs, FIELDS)
    write_toml(MEDIA / "maps.toml",
               "# Public domain Bible and church history maps for the He Lives library.\n"
               "# Generated by pipeline/media/build_catalogs.py; files live under public/.",
               "map", mps, FIELDS + ["region", "period"])
    print(f"images.toml: {len(imgs)} written, {len(img_pending)} pending")
    print(f"maps.toml: {len(mps)} written, {len(map_pending)} pending")
    (CACHE / "pending_catalog.json").write_text(json.dumps({"images": img_pending, "maps": map_pending}, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
