"""Verify curated videos with YouTube oEmbed and write media/videos.toml.

Title and channel come from oEmbed, never from the curated list.
Duration comes from the cached search result for the same id.
Run: python3 pipeline/media/build_videos.py
"""
from __future__ import annotations

import json
import re
import sys

sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parent))

from common import CACHE, MEDIA, write_toml  # noqa: E402
from videos_data import BP_OVERVIEWS, VIDEOS  # noqa: E402
from yt import oembed  # noqa: E402

ALLOWED_CHANNELS = {
    "BibleProject", "Ryan M Reeves", "Ligonier Ministries", "Gavin Ortlund", "Wes Huff",
    "Apologetics Canada", "Sola Media", "The Thomistic Institute", "Bishop Robert Barron",
    "EWTN News", "EWTN", "Catholic Culture", "gonzagasocraticclub",
}


def slug(s: str, n: int = 64) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
    return s[:n].rstrip("-")


def load_index() -> dict:
    p = CACHE / "video_index.json"
    return json.loads(p.read_text()) if p.exists() else {}


def entries() -> list[tuple[str, list[str], str]]:
    out = []
    for vid, (books, desc) in BP_OVERVIEWS.items():
        tags = [f"bible:{b}" for b in books] or ["topic:bible-overview"]
        out.append((vid, tags + ["topic:book-overview"], desc))
    out.extend(VIDEOS)
    return out


def main() -> int:
    idx = load_index()
    rows, rejected, seen_ids, seen_vids = [], [], set(), set()
    for vid, tags, desc in entries():
        if vid in seen_vids:
            rejected.append({"id": vid, "why": "duplicate in curated list"})
            continue
        seen_vids.add(vid)
        status, meta = oembed(vid, cache=True)
        if status != 200 or not meta.get("title"):
            rejected.append({"id": vid, "why": f"oEmbed HTTP {status}"})
            continue
        channel = meta.get("author_name", "").strip()
        if channel not in ALLOWED_CHANNELS:
            rejected.append({"id": vid, "why": f"channel not on allowlist: {channel}"})
            continue
        title = meta["title"]
        base = slug(f"{channel}-{title}")
        rid = base
        n = 2
        while rid in seen_ids:
            rid = f"{base}-{n}"
            n += 1
        seen_ids.add(rid)
        rows.append({
            "id": rid,
            "title": title,
            "channel": channel,
            "url": f"https://www.youtube.com/watch?v={vid}",
            "duration": idx.get(vid, {}).get("duration", ""),
            "tags": tags,
            "description": desc,
        })
    header = ("# Curated videos for the He Lives library.\n"
              "# Generated by pipeline/media/build_videos.py. Title and channel are taken from\n"
              "# YouTube oEmbed; every entry passed oEmbed when this file was written.")
    write_toml(MEDIA / "videos.toml", header, "video", rows,
               ["id", "title", "channel", "url", "duration", "tags", "description"])
    (CACHE / "rejected_videos.json").write_text(json.dumps(rejected, indent=1))
    missing = [r["url"] for r in rows if not r["duration"]]
    print(f"videos written: {len(rows)}  rejected: {len(rejected)}  no duration: {len(missing)}")
    for r in rejected:
        print("  rejected", r["id"], r["why"])
    for m in missing:
        print("  no duration", m)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
